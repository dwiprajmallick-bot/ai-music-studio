function initPageLanguage() {
    const currentLang = localStorage.getItem("selected_site_lang") || "bn";
    applyTranslations(currentLang);

    const selector = document.getElementById("subPageLangSelect");
    if (selector) {
        selector.value = currentLang;
        selector.addEventListener("change", (e) => {
            const lang = e.target.value;
            localStorage.setItem("selected_site_lang", lang);
            applyTranslations(lang);
        });
    }
}

function applyTranslations(lang) {
    const t = pageTranslations[lang] || pageTranslations["en"];
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (t[key]) {
            el.innerText = t[key];
        }
    });
}

document.addEventListener("DOMContentLoaded", initPageLanguage);
